<?php

namespace App\Services;

use App\Models\User;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Mail;
use Illuminate\Validation\ValidationException;
use Throwable;

class EmailOtpService
{
    private const EXPIRY_MINUTES = 10;
    private const MAX_ATTEMPTS = 5;
    private const RESEND_SECONDS = 60;

    public function send(User $user): void
    {
        if ($user->email_verified_at !== null) {
            throw ValidationException::withMessages([
                'email' => 'Email is already verified.',
            ]);
        }

        $this->sendCode($user, 'email_verification');
    }

    public function verify(User $user, string $code): bool
    {
        return DB::transaction(function () use ($user, $code) {
            $user = User::query()
                ->whereKey($user->id)
                ->lockForUpdate()
                ->firstOrFail();

            if ($user->email_verified_at !== null) {
                return true;
            }

            if (! $this->consumeCode(
                $user->email,
                'email_verification',
                $code
            )) {
                return false;
            }

            $user->forceFill([
                'email_verified_at' => now(),
            ])->save();

            return true;
        }, 3);
    }

    public function sendPasswordReset(User $user): void
    {
        $this->sendCode($user, 'password_reset');
    }

    public function resetPassword(
        User $user,
        string $code,
        string $password
    ): bool {
        return DB::transaction(function () use (
            $user,
            $code,
            $password
        ) {
            $user = User::query()
                ->whereKey($user->id)
                ->lockForUpdate()
                ->firstOrFail();

            if (! $this->consumeCode(
                $user->email,
                'password_reset',
                $code
            )) {
                return false;
            }

            $user->forceFill([
                'password' => Hash::make($password),
            ])->save();

            // Revoke previous API sessions.
            $user->tokens()->delete();

            return true;
        }, 3);
    }

    private function sendCode(
        User $user,
        string $purpose
    ): void {
        $code = (string) random_int(100000, 999999);
        $hashedCode = Hash::make($code);

        DB::transaction(function () use (
            $user,
            $purpose,
            $hashedCode
        ) {
            $lockedUser = User::query()
                ->whereKey($user->id)
                ->lockForUpdate()
                ->firstOrFail();

            $recent = DB::table('verification_codes')
                ->where('channel', 'email')
                ->where('identifier', $lockedUser->email)
                ->where('purpose', $purpose)
                ->where(
                    'created_at',
                    '>',
                    now()->subSeconds(self::RESEND_SECONDS)
                )
                ->exists();

            if ($recent) {
                throw ValidationException::withMessages([
                    'email' => 'Please wait before requesting another code.',
                ]);
            }

            DB::table('verification_codes')
                ->where('channel', 'email')
                ->where('identifier', $lockedUser->email)
                ->where('purpose', $purpose)
                ->delete();

            DB::table('verification_codes')->insert([
                'channel' => 'email',
                'identifier' => $lockedUser->email,
                'purpose' => $purpose,
                'code' => $hashedCode,
                'expires_at' => now()->addMinutes(
                    self::EXPIRY_MINUTES
                ),
                'attempts' => 0,
                'created_at' => now(),
                'updated_at' => now(),
            ]);
        }, 3);

        $subject = $purpose === 'password_reset'
            ? 'Marketplace Password Reset Code'
            : 'Marketplace Email Verification Code';

        try {
            // Do not hold database locks during SMTP delivery.
            Mail::raw(
                "Your Marketplace verification code is: {$code}\n\n"
                ."This code expires in 10 minutes.\n"
                ."Do not share it with anyone.",
                function ($message) use ($user, $subject) {
                    $message->to($user->email)
                        ->subject($subject);
                }
            );
        } catch (Throwable $exception) {
            // Remove only the OTP generated by this request.
            DB::table('verification_codes')
                ->where('channel', 'email')
                ->where('identifier', $user->email)
                ->where('purpose', $purpose)
                ->where('code', $hashedCode)
                ->delete();

            throw $exception;
        }
    }

    private function consumeCode(
        string $email,
        string $purpose,
        string $code
    ): bool {
        $record = DB::table('verification_codes')
            ->where('channel', 'email')
            ->where('identifier', $email)
            ->where('purpose', $purpose)
            ->lockForUpdate()
            ->first();

        if (! $record) {
            return false;
        }

        if (
            now()->greaterThanOrEqualTo($record->expires_at)
            || $record->attempts >= self::MAX_ATTEMPTS
        ) {
            DB::table('verification_codes')
                ->where('id', $record->id)
                ->delete();

            return false;
        }

        if (! Hash::check($code, $record->code)) {
            DB::table('verification_codes')
                ->where('id', $record->id)
                ->update([
                    'attempts' => $record->attempts + 1,
                    'updated_at' => now(),
                ]);

            // Return false so transaction commits attempt count.
            return false;
        }

        DB::table('verification_codes')
            ->where('id', $record->id)
            ->delete();

        return true;
    }
}
